#!/usr/bin/env bash
# One training task on a rented GPU node (e.g. an AWS g6e instance; see docs/cloud_training.md).
#
#   DV_DATA=s3://<bucket>/data/drawing_vla DV_OUT=s3://<bucket>/checkpoints/drawing_vla/runs/<task> \
#       bash scripts/cloud_task.sh <stage> [<stage> ...]          # stages of scripts/goal_pipeline.sh
#
# - fetches what the stages need from $DV_DATA: goal_v1.tar (overfit / G / N) and quickdraw_processed.tar
#   (classifier / generator; without it the quickdraw stage downloads Quick, Draw! itself)
# - uses the environment baked into the training image ($DV_VENV, docker/Dockerfile.train) when there is one;
#   otherwise prepares it with uv, and if the default CUDA 13 torch cannot see the GPU (driver < 580) switches to the
#   CUDA 12.8 wheels of the same version; if torchcodec has no system FFmpeg, videos are decoded with pyav
# - syncs outputs/ and logs/ to $DV_OUT every 15 min and at the end (also when a stage fails)
set -euo pipefail
cd "$(dirname "$0")/.."
: "${DV_DATA:?DV_DATA (s3 prefix of the data)}" "${DV_OUT:?DV_OUT (s3 prefix for the results of this task)}"
STAGES=" $* "
has() { for s in "$@"; do [[ "$STAGES" == *" $s "* ]] && return 0; done; return 1; }
say() { echo "[$(date '+%m-%d %H:%M:%S')] cloud_task: $*"; }
export PATH="$HOME/.local/bin:$PATH"
if [ -x "${DV_VENV:-/nonexistent}/bin/python" ]; then
    export OEKAKI_PY="env PYTHONPATH=$PWD $DV_VENV/bin/python"   # the image venv has no project install; use this tree
else
    export OEKAKI_PY="env -u PYTHONPATH .venv/bin/python"
fi
PY=$OEKAKI_PY
mkdir -p outputs logs

sync_out() { aws s3 sync outputs/ "$DV_OUT/outputs/" --only-show-errors || true
             aws s3 sync logs/ "$DV_OUT/logs/" --only-show-errors || true; }
( while sleep 900; do sync_out; done ) &
SYNC_PID=$!
trap 'kill $SYNC_PID 2>/dev/null || true; sync_out; say "synced to $DV_OUT"' EXIT

say "host $(hostname)  stages:$STAGES"
nvidia-smi --query-gpu=index,name,driver_version,memory.total --format=csv,noheader || true

# ---- inputs ----
if has overfit G N G_long && [ ! -d data/goal_v1/G ]; then
    say "fetching goal_v1.tar"; aws s3 cp "$DV_DATA/goal_v1.tar" - --only-show-errors | tar x
fi
if has G_2x G_pair && [ ! -d data/goal_v2/G ]; then
    # dataset goal_v2 is generated by another task (datagen_goal_v2); wait for its tar (an S3 object appears only when
    # the upload is complete)
    for _ in $(seq 1 720); do aws s3 ls "$DV_DATA/goal_v2.tar" > /dev/null 2>&1 && break; sleep 30; done
    say "fetching goal_v2.tar"; aws s3 cp "$DV_DATA/goal_v2.tar" - --only-show-errors | tar x
fi
if has classifier generator datagen_goal_v2 && [ ! -d data/quickdraw/processed ]; then
    if aws s3 ls "$DV_DATA/quickdraw_processed.tar" > /dev/null 2>&1; then
        say "fetching quickdraw_processed.tar"; aws s3 cp "$DV_DATA/quickdraw_processed.tar" - --only-show-errors | tar x
    else
        STAGES=" quickdraw$STAGES"
    fi
fi

# ---- environment ----
if [ -z "${DV_VENV:-}" ] || [ ! -x "$DV_VENV/bin/python" ]; then
    command -v uv > /dev/null || curl -LsSf https://astral.sh/uv/install.sh | sh
    uv sync --frozen
fi
if ! $PY -c "import sys, torch; sys.exit(0 if torch.cuda.is_available() else 1)"; then
    tv=$($PY -c "import torch, torchvision; print(torch.__version__.split('+')[0], torchvision.__version__.split('+')[0])")
    say "torch cannot use the GPU; installing the cu128 wheels of torch/torchvision ${tv}"
    uv pip install --python "$($PY -c 'import sys; print(sys.executable)')" --reinstall --index-url https://download.pytorch.org/whl/cu128 \
        "torch==${tv% *}" "torchvision==${tv#* }"
fi
$PY -c "import torch; assert torch.cuda.is_available(), 'no CUDA'; print('torch', torch.__version__, torch.cuda.get_device_name(0))"
if has overfit G N G_long G_2x G_pair && ! $PY -c "from torchcodec.decoders import VideoDecoder" > /dev/null 2>&1; then
    say "torchcodec cannot load FFmpeg; decoding videos with pyav"; export OEKAKI_VIDEO_BACKEND=pyav
fi

# ---- stages ----
for s in $STAGES; do
    say "stage $s"; bash scripts/goal_pipeline.sh "$s"
done
if has datagen_goal_v2; then
    say "uploading goal_v2.tar"; tar cf - data/goal_v2 | aws s3 cp - "$DV_DATA/goal_v2.tar" --only-show-errors
fi
say "all stages done"
